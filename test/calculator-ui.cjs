'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const app=require('../server');
(async()=>{
 const server=await new Promise(resolve=>{const s=app.listen(3000,'127.0.0.1',()=>resolve(s));});
 let browser;
 try {
  browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || '/usr/bin/chromium',args:['--no-sandbox']});
  const page=await browser.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const waitCalculation=()=>page.waitForResponse(r=>r.url().endsWith('/api/calculator/calculate')&&r.request().method()==='POST',{timeout:30000});
  const initial=waitCalculation();
  const base='http://127.0.0.1:'+server.address().port;
  const html=await page.goto(base+'/calculator.html');
  assert.match((await html.allHeaders())['cache-control'],/no-store/);
  const script=await page.request.get(base+'/js/calculator.js?v=20261030-module-catalog-r9');
  assert.match(script.headers()['cache-control'],/no-store/);
  assert.match(await script.text(),/function updateInputGuidance/);
  const initialResponse=await initial;
  assert.equal(initialResponse.status(),200);
  const initialResult=await initialResponse.json();
  assert.equal(initialResponse.request().postDataJSON().designMode,'document');
  assert.equal(initialResult.input.designMode,'document');
  assert.equal(initialResult.input.vocMargin,0);
  assert.equal(initialResult.selection.requiresFullAllocation,true);
  assert.equal(initialResult.plans.B.acKW,408);
  assert.equal(initialResult.allocations.B.allocated,620);
  assert.equal(initialResult.allocations.B.unallocated,0);
  await page.waitForFunction(()=>document.querySelectorAll('#planComparisonBody tr').length===3);
  assert.equal(await page.locator('.choice[data-choice="A"]').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('.result-card[data-card="A"]').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('.choice[data-choice="B"]').getAttribute('aria-pressed'),'false');
  const initialBRow=await page.locator('#planComparisonBody tr').nth(1).innerText();
  assert.match(initialBRow,/408kW/);assert.match(initialBRow,/620장 \/ 0장/);
  await page.click('.result-card[data-card="B"]');
  assert.match(await page.locator('#mpptSummary').innerText(),/연결 620장 \/ 미배분 0장/);
  assert.match(await page.locator('.result-card[data-card="B"]').innerText(),/전체 620장 연결/);
  assert.equal(await page.inputValue('#designMode'),'document');
  assert.equal(await page.inputValue('#vocMargin'),'0');assert.equal(await page.inputValue('#iscFactor'),'1.25');
  const assertGuidance=async(basis,expected)=>{
    assert.deepEqual(await page.locator('.guided-input').evaluateAll(nodes=>nodes.map(n=>n.id).sort()),expected.slice().sort());
    assert.equal(await page.locator('#plantCapacity').evaluate(n=>n.readOnly),basis==='modules');
    assert.equal(await page.locator('#moduleCount').evaluate(n=>n.readOnly),basis==='capacity');
    assert.equal(await page.locator('#acVoltage').isEnabled(),true);
    assert.equal(await page.locator('label[for="plantCapacity"] [data-auto-badge]').isVisible(),basis==='modules');
    assert.equal(await page.locator('label[for="moduleCount"] [data-auto-badge]').isVisible(),basis==='capacity');
    assert.match(await page.locator('label[for="manufacturer"] [data-input-badge]').innerText(),basis==='modules'?/1 선택/:/2 선택/);
  };
  await assertGuidance('capacity',['plantCapacity','manufacturer','acVoltage']);
  await page.locator('section[aria-labelledby="input-title"]').screenshot({path:'/tmp/calculator-input-capacity.png'});
  await page.check('input[name="basis"][value="modules"]');
  await assertGuidance('modules',['manufacturer','moduleCount']);
  await page.fill('#moduleCount','700');
  assert.equal(await page.inputValue('#plantCapacity'),'451.500');
  const modulesCalculation=waitCalculation();await page.click('#runBtn');
  const modulesResponse=await modulesCalculation;
  assert.equal(modulesResponse.request().postDataJSON().basis,'modules');
  const moduleResult=await modulesResponse.json();
  assert.equal(moduleResult.input.moduleCount,700);assert.equal(moduleResult.input.dcKW,451.5);
  await page.waitForFunction(()=>document.querySelectorAll('#planComparisonBody tr').length===3);
  assert.equal(await page.locator('.choice[data-choice="B"]').getAttribute('aria-pressed'),'true');
  assert.equal(moduleResult.allocations.B.unallocated,0);
  await page.locator('section[aria-labelledby="input-title"]').screenshot({path:'/tmp/calculator-input-modules.png'});
  await page.check('input[name="basis"][value="capacity"]');
  await assertGuidance('capacity',['plantCapacity','manufacturer','acVoltage']);
  await page.selectOption('#series','NJ-ES 시리즈');
  await page.selectOption('#model','HiS-T645NJ-ES');
  assert.equal(await page.inputValue('#vmpCoefficient'),'-0.25');
  const chooseStandard=waitCalculation();
  await page.selectOption('#designMode','standard');
  assert.equal((await chooseStandard).status(),200);
  assert.equal(await page.inputValue('#vocMargin'),'5');
  await page.fill('#plantCapacity','500');
  await page.fill('#minTemperature','-10');
  await page.fill('#maxCellTemperature','70');
  await page.fill('#rearIrradiance','10');
  await page.fill('#vocMargin','3');
  await page.fill('#iscFactor','1.1');
  assert.match(await page.locator('label[for="maxCellTemperature"]').innerText(),/고온 Vmpp 계산용 온도/);
  const doc=waitCalculation();
  await page.selectOption('#designMode','document');
  assert.equal(await page.inputValue('#vocMargin'),'0');assert.equal(await page.inputValue('#rearIrradiance'),'13.5');
  const docResponse=await doc;
  const sent=docResponse.request().postDataJSON();
  for(const [key,value] of Object.entries({designMode:'document',minTemperature:-20,maxCellTemperature:40,rearIrradiance:13.5,vocMargin:0,iscFactor:1.25})) assert.equal(sent[key],value,key);
  const documentResult=await docResponse.json();
  assert.equal(documentResult.input.vocMargin,0);
  assert.equal(documentResult.input.maxCellTemperature,40);
  assert.deepEqual(documentResult.plans.A.metrics.strings,{'14':5,'15':47});
  assert.equal(documentResult.plans.B.acKW,502);
  assert.equal(documentResult.allocations.B.allocated,775);
  assert.equal(documentResult.allocations.B.unallocated,0);
  await page.waitForFunction(()=>document.querySelector('#planComparisonBody')?.textContent.includes('15직렬 47개'));
  await page.click('.result-card[data-card="A"]');
  await page.check('#showVerificationDetails');
  assert.match(await page.locator('#verifyBody').innerText(),/STC Voc 사용/);
  assert.match(await page.locator('#comparisonWarnings').innerText(),/자료 재현/);
  const standard=waitCalculation();
  await page.selectOption('#designMode','standard');
  assert.equal(await page.inputValue('#vocMargin'),'5');assert.equal(await page.inputValue('#iscFactor'),'1.25');
  const standardResponse=await standard;
  assert.equal(standardResponse.request().postDataJSON().vocMargin,5);
  const result=await standardResponse.json();
  assert.equal(result.input.vocMargin,5);
  assert.deepEqual(result.plans.A.metrics.strings,{'13':9,'14':47});
  await page.waitForFunction(()=>document.querySelector('#planComparisonBody')?.textContent.includes('14직렬 47개'));
  assert.match(await page.locator('#comparisonWarnings').innerText(),/1012.41V/);
  // Manual edits after a preset must be sent and calculated as entered.
  await page.fill('#maxCellTemperature','45');
  await page.fill('#vocMargin','4');
  const manual=waitCalculation();await page.click('#runBtn');
  const manualResponse=await manual;
  const manualResult=await manualResponse.json();
  assert.equal(manualResponse.request().postDataJSON().maxCellTemperature,45);
  assert.equal(manualResult.input.maxCellTemperature,45);
  assert.equal(manualResult.input.vocMargin,4);
  await page.waitForFunction(()=>document.querySelector('#assumptionSummary')?.textContent.includes('45℃'));
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.locator('#planComparisonBody').isVisible());
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert.equal(overflow,false,'mobile page should not overflow horizontally');
  await page.check('input[name="basis"][value="modules"]');
  await assertGuidance('modules',['manufacturer','moduleCount']);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  // No incomplete B fallback: clear all previous results when no plan qualifies.
  await page.check('input[name="basis"][value="capacity"]');
  await page.fill('#plantCapacity','1');
  const empty=waitCalculation();await page.click('#runBtn');
  const emptyResult=await (await empty).json();
  for(const id of ['A','B','C'])assert.equal(emptyResult.plans[id],null);
  await page.waitForFunction(()=>document.querySelector('#mpptGrid')?.textContent.includes('구성안을 찾지 못했습니다'));
  assert.equal(await page.locator('.result-card:disabled').count(),3);
  assert.equal(await page.locator('.choice[aria-pressed="true"]').count(),0);
  assert.equal(await page.locator('#inverterPreview').isDisabled(),true);
  assert.equal(await page.locator('#verifyBody').innerText(),'');
  assert.equal(await page.locator('#fuseReview').isVisible(),false);
  // A valid calculation after an empty result restores the chosen available plan.
  await page.selectOption('#series','NA 시리즈');
  await page.selectOption('#model','HiC-T645OJ');
  await page.fill('#plantCapacity','400');
  const restored=waitCalculation();await page.selectOption('#designMode','document');
  assert.equal((await (await restored).json()).allocations.B.unallocated,0);
  await page.waitForFunction(()=>document.querySelector('.choice[data-choice="A"]')?.getAttribute('aria-pressed')==='true');
  // A stale backend must produce an actionable message instead of silent failure.
  await page.route('**/api/calculator/calculate',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({plans:{},input:{}})}));
  await page.click('#runBtn');
  await page.waitForFunction(()=>document.querySelector('#inputMessage')?.textContent.includes('서버가 이전 버전'));
  assert.match(await page.locator('#inputMessage').innerText(),/재시작/);
  // The previous engine had selection metadata but could still return partial B.
  const legacy=JSON.parse(JSON.stringify(initialResult));delete legacy.selection.requiresFullAllocation;
  await page.unroute('**/api/calculator/calculate');
  await page.route('**/api/calculator/calculate',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(legacy)}));
  await page.click('#runBtn');
  await page.waitForFunction(()=>document.querySelector('#inputMessage')?.textContent.includes('서버가 이전 버전'));
  assert.deepEqual(errors,[]);
  console.log('PASS: full-allocation B at 400/500 kW, no incomplete fallback, empty-result recovery, default document mode and A selection, preserved user selection, input guidance, module-count calculation, preset recalculation, manual edits, mobile layout, cache headers, stale-backend messages');
 }finally{
  if(browser) await browser.close();
  await new Promise(resolve=>server.close(resolve));
 }
})().then(()=>process.exit(0)).catch(error=>{console.error(error);process.exit(1)});
